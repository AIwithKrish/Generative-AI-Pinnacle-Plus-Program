def format_message_steps(messages):
    """
    Convert a list of message-like objects into a readable step log.
    Accepts dicts ({role, content, tool_calls}), strings, or objects with .content/.type.
    """
    steps = []

    for message in messages:
        # If it's a dict (OpenAI-style)
        if isinstance(message, dict):
            role = message.get("role") or message.get("type")
            content = message.get("content") or message.get("text") or ""
            tool_calls = message.get("tool_calls") or []

        # If it's an object (e.g., LangChain BaseMessage)
        elif hasattr(message, "content"):
            role = getattr(message, "type", None) or getattr(message, "role", None)
            content = getattr(message, "content", "")
            tool_calls = getattr(message, "tool_calls", []) or []

        # Fallback: treat as assistant text
        else:
            role = "assistant"
            content = str(message)
            tool_calls = []

        # Map roles to lines
        if role in ("user", "human"):
            steps.append(f"User: {content}")
        elif role == "system":
            steps.append("System: Provided context")
        elif role in ("assistant", "ai"):
            if tool_calls:
                for tc in tool_calls:
                    # handle both {"function":{"name":...}} and {"name":...} shapes
                    fn = (
                        (tc.get("function") or {}).get("name")
                        if isinstance(tc, dict)
                        else None
                    )
                    name = fn or (tc.get("name") if isinstance(tc, dict) else "unknown")
                    steps.append(f"Assistant: Called tool '{name}'")
            else:
                steps.append(f"Assistant: {content}")
        elif role in ("tool", "function"):
            steps.append(f"Tool response: {content}")
        else:
            # Unknown role; still show content
            steps.append(f"{role or 'Message'}: {content}")

    return "\n".join(steps)


def _to_message_dict(m):
    if isinstance(m, dict):
        return m
    if hasattr(m, "content"):
        # LangChain/BaseMessage style
        return {
            "role": getattr(m, "type", None) or getattr(m, "role", "assistant"),
            "content": getattr(m, "content", ""),
        }
    # String or anything else -> treat as assistant message
    return {"role": "assistant", "content": str(m)}


def run_agent_and_track_path(example: Example):
    messages = [{"role": "user", "content": example.input.get("question")}]
    ret = run_agent(messages)

    # Ensure we have a list (some frameworks return a dict with 'messages')
    if isinstance(ret, dict) and "messages" in ret:
        history = ret["messages"]
    else:
        history = ret

    # Normalize each entry
    history = [_to_message_dict(m) for m in history]

    return {
        "path_length": len(history),
        "messages": format_message_steps(history),  # now safe
    }


